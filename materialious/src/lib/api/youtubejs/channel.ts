function getSubscriberCountText(channel: YT.Channel): string | undefined {
	const header = channel.header;

	if (header?.is(YTNodes.C4TabbedHeader)) {
		return header.subscribers?.toString();
	}

	if (header?.is(YTNodes.InteractiveTabbedHeader)) {
		const metadata = header.metadata?.toString();
		return metadata && /subscriber/i.test(metadata) ? metadata : undefined;
	}

	if (header?.is(YTNodes.PageHeader)) {
		const metadataParts =
			header.content?.metadata?.metadata_rows.flatMap(
				(row) => row.metadata_parts?.map((part) => part.text?.toString() ?? '') ?? []
			) ?? [];

		return (
			metadataParts.find((part) => /subscriber/i.test(part)) ??
			metadataParts.find((part) => /^\s*\d[\d,.]*\s*[KMBT]?\b/i.test(part))
		);
	}

	return undefined;
}

function parseSubscriberCount(countText: string | undefined): number {
	if (!countText) return 0;

	const match = countText.match(/([\d,.]+)\s*([KMBT])?/i);
	if (!match) return 0;

	const countTextValue = match[1] ?? '';
	const normalizedCount =
		match[2] && countTextValue.includes(',') && !countTextValue.includes('.')
			? countTextValue.replace(',', '.')
			: countTextValue.replace(/,/g, '');
	const count = Number(normalizedCount);
	const suffix = match[2]?.toUpperCase();
	const multipliers: Record<string, number> = {
		K: 1_000,
		M: 1_000_000,
		B: 1_000_000_000,
		T: 1_000_000_000_000
	};
	const multiplier = multipliers[suffix ?? ''] ?? 1;

	return Math.round(count * multiplier);
}

export async function getChannelYTjs(channelId: string): Promise<ChannelPage> {
	const innertube = await getInnertube();

	const innerResults = await innertube.getChannel(channelId);

	let authorBanners: Image[] = [];
	const header = innerResults.header;
	if (header?.is(YTNodes.C4TabbedHeader)) {
		authorBanners = header.banner ?? header.mobile_banner ?? header.tv_banner ?? [];
	} else if (header?.is(YTNodes.InteractiveTabbedHeader)) {
		authorBanners = header.banner ?? [];
	} else if (header?.is(YTNodes.PageHeader) && header.content?.is(YTNodes.PageHeaderView)) {
		authorBanners = header.content.banner?.image ?? [];
	}

	if (innerResults.metadata.avatar) await associateAvatar(channelId, innerResults.metadata.avatar);

	const description = innerResults.metadata.description ?? '';
	const subCount = parseSubscriberCount(getSubscriberCountText(innerResults));

	return {
		type: 'channel',
		allowedRegions: innerResults.metadata.available_countries ?? [],
		tabs: innerResults.tabs.map((tab) => tab.toLowerCase().replace('live', 'streams')),
		latestVideos: [],
		isFamilyFriendly: true,
		author: innerResults.metadata.title ?? '',
		authorThumbnails: innerResults.metadata.avatar ?? [],
		authorId: channelId,
		authorBanners,
		joined: 0,
		authorVerified: true,
		totalViews: 0,
		authorUrl: `/channel/${channelId}`,
		subCount,
		autoGenerated: false,
		description,
		descriptionHml: description
	};
}

export function invidiousChannelContentSchema(
	innerResults: YT.Channel | YT.ChannelListContinuation | YT.FilteredChannelList,
	author: string,
	authorId: string
) {
	const videos: Video[] = [];

	let contents;
	if (
		innerResults instanceof YT.Channel &&
		innerResults.current_tab?.content?.is(YTNodes.RichGrid)
	) {
		contents = innerResults.current_tab.content.contents;
	} else if (
		innerResults instanceof YT.ChannelListContinuation &&
		innerResults.contents?.is(YTNodes.AppendContinuationItemsAction)
	) {
		contents = innerResults.contents.contents;
	} else if (
		innerResults instanceof YT.FilteredChannelList &&
		innerResults.contents?.is(ReloadContinuationItemsCommand, YTNodes.AppendContinuationItemsAction)
	) {
		contents = innerResults.contents.contents;
	}

	if (!contents) return videos;

	contents.forEach((item) => {
		if (item.is(YTNodes.RichItem)) {
			const invidiousSchema = invidiousItemSchema(item.content);
			if (invidiousSchema?.type === 'video') {
				invidiousSchema.author = author;
				invidiousSchema.authorId = authorId;
				videos.push(invidiousSchema);
			}
		}
	});

	return videos;
}

function fetchChannelContentVideosWithContinuation(
	innerResults: YT.ChannelListContinuation | YT.FilteredChannelList,
	author: string,
	authorId: string
): () => Promise<ChannelContentVideos> {
	return async () => {
		const continuation = await innerResults.getContinuation();
		return {
			videos: invidiousChannelContentSchema(continuation, author, authorId),
			getContinuation: fetchChannelContentVideosWithContinuation(continuation, author, authorId)
		};
	};
}

async function fetchChannelContentWithContinuation(
	innerResults: YT.Channel | YT.ChannelListContinuation | YT.FilteredChannelList,
	author: string,
	authorId: string
): Promise<ChannelContent> {
	const channelContent: ChannelContent = {
		continuation: innerResults.has_continuation ? 'logicalPlaceholder' : undefined,
		videos: invidiousChannelContentSchema(innerResults, author, authorId)
	};

	if (channelContent.continuation) {
		channelContent.getContinuation = fetchChannelContentVideosWithContinuation(
			innerResults,
			author,
			authorId
		);
	}

	return channelContent;
}

export async function getChannelContentYTjs(
	channelId: string,
	options: ChannelOptions
): Promise<ChannelContent> {
	const innertube = await getInnertube();

	const channel = await innertube.getChannel(channelId);

	const author = channel.metadata.title ?? '';

	let innerResults: YT.Channel | YT.ChannelListContinuation | YT.FilteredChannelList;
	if (options.type === 'videos') {
		if (!channel.hasTabWithURL('videos')) return { videos: [] };
		innerResults = await channel.getVideos();
	} else if (options.type === 'playlists') {
		innerResults = await channel.getPlaylists();
	} else if (options.type === 'shorts') {
		innerResults = await channel.getShorts();
	} else {
		innerResults = await channel.getLiveStreams();
	}

	if (options.sortBy && innerResults instanceof YT.Channel) {
		const sortBy = options.sortBy;
		const sortFilterLabels: Record<NonNullable<ChannelOptions['sortBy']>, [string, ...string[]]> = {
			newest: ['Latest', 'Newest'],
			oldest: ['Oldest'],
			popular: ['Popular']
		};
		const preferredLabels = sortFilterLabels[sortBy];
		try {
			const sortFilter = innerResults.filters.find((filter) =>
				preferredLabels.some((label) => filter.toLowerCase() === label.toLowerCase())
			);
			if (sortFilter) {
				innerResults = await innerResults.applyFilter(sortFilter);
			} else {
				const legacyFilter = innerResults.sort_filters.find((filter) =>
					preferredLabels.some((label) => filter.toLowerCase() === label.toLowerCase())
				);
				if (legacyFilter) innerResults = await innerResults.applySort(legacyFilter);
			}
		} catch {
			// sort filter not available for this tab
		}
	}

	return fetchChannelContentWithContinuation(innerResults, author, channelId);
}
